"""Generate Databricks Unity Catalog SQL from the governance YAML and contracts.

NOT EXECUTED IN THIS REPO. The files in ``deploy/unity_catalog/`` are compiled here so the
platform configuration comes from the same YAML that CI validates; applying them is a manual
step documented in ``deploy/unity_catalog/README.md``.
"""

from __future__ import annotations

from pathlib import Path

from . import access, grants
from . import contracts as contracts_mod
from .paths import root

CATALOG = "governance_demo"
BANNER = ("-- NOT EXECUTED IN THIS REPO. Generated by `govkit deploy` from governance/*.yaml and contracts/.\n"
          "-- Review before running in Databricks (see deploy/unity_catalog/README.md). Do not edit by hand.\n\n")
TYPES = {"VARCHAR": "STRING", "INTEGER": "INT", "BIGINT": "BIGINT", "DOUBLE": "DOUBLE", "DATE": "DATE",
         "BOOLEAN": "BOOLEAN", "TIMESTAMP": "TIMESTAMP"}
SCHEMA_COMMENTS = {
    "bronze": "Raw data as received from source systems. Not published to consumers.",
    "silver": "Validated, standardised data. Rows failing blocking rules are quarantined upstream.",
    "gold": "Business-ready data products with data contracts.",
}


def _q(text: str) -> str:
    return "'" + str(text).replace("'", "\\'") + "'"


def _fq(name: str) -> str:
    return f"{CATALOG}.{name}"


def catalog_sql() -> str:
    lines = [f"CREATE CATALOG IF NOT EXISTS {CATALOG} COMMENT 'Governance-as-code demo (synthetic data).';", ""]
    for schema, comment in SCHEMA_COMMENTS.items():
        lines.append(f"CREATE SCHEMA IF NOT EXISTS {CATALOG}.{schema} COMMENT {_q(comment)};")
    return BANNER + "\n".join(lines) + "\n"


def tables_sql() -> str:
    out = []
    for c in contracts_mod.load_all():
        cols = []
        for p in c.properties:
            null = " NOT NULL" if p.required or p.primary_key else ""
            cols.append(f"  {p.name} {TYPES.get(p.physical_type, 'STRING')}{null} COMMENT {_q(p.description)}")
        if c.primary_key:
            cols.append(f"  CONSTRAINT pk_{c.table} PRIMARY KEY ({', '.join(c.primary_key)})")
        out.append(f"CREATE TABLE IF NOT EXISTS {_fq(c.name)} (\n" + ",\n".join(cols)
                   + f"\n) COMMENT {_q(f'{c.purpose} Contract {c.id} v{c.version}.')};\n")
    return BANNER + "\n".join(out)


def tags_sql() -> str:
    out = []
    for c in contracts_mod.load_all():
        tags = {"classification": c.classification, "domain": c.domain, "data_owner": c.owner,
                "data_steward": c.steward, "contract_version": c.version, "layer": c.layer}
        out.append(f"ALTER TABLE {_fq(c.name)} SET TAGS ("
                   + ", ".join(f"{_q(k)} = {_q(v)}" for k, v in tags.items()) + ");")
        for p in c.properties:
            col_tags = {}
            if p.pii:
                col_tags["pii"] = p.pii
            if p.business_name:
                col_tags["glossary_term"] = p.business_name
            if col_tags:
                out.append(f"ALTER TABLE {_fq(c.name)} ALTER COLUMN {p.name} SET TAGS ("
                           + ", ".join(f"{_q(k)} = {_q(v)}" for k, v in col_tags.items()) + ");")
        out.append("")
    return BANNER + "\n".join(out)


def grants_sql() -> str:
    governed = {c.name for c in contracts_mod.load_all()}
    members = grants.groups()
    users = access.users()
    lines = ["-- Groups must exist first (workspace or account identity settings). Membership derived from users.yaml:"]
    for g, uids in sorted(members.items()):
        lines.append(f"--   {g}: " + (", ".join(users[u]["email"] for u in sorted(uids)) or "(no members)"))
    lines.append("")
    compiled = [g for g in grants.compile_grants() if g.dataset in governed]
    principals = sorted({g.principal for g in compiled})
    schemas = sorted({(g.principal, g.dataset.split(".")[0]) for g in compiled})
    for p in principals:
        lines.append(f"GRANT USE CATALOG ON CATALOG {CATALOG} TO `{p}`;")
    for p, s in schemas:
        lines.append(f"GRANT USE SCHEMA ON SCHEMA {CATALOG}.{s} TO `{p}`;")
    lines.append("")
    for g in compiled:
        note = f"  -- {g.note}" if g.note else ""
        lines.append(f"GRANT SELECT ON TABLE {_fq(g.dataset)} TO `{g.principal}`;{note}")
    lines += ["", "-- Time-bound grants above must be revoked on expiry, e.g.:"]
    for g in compiled:
        if g.kind == "user":
            lines.append(f"-- REVOKE SELECT ON TABLE {_fq(g.dataset)} FROM `{g.principal}`;  -- {g.note}")
    return BANNER + "\n".join(lines) + "\n"


MASKS = {
    "email": "concat(left(v, 1), '***@', split_part(v, '@', 2))",
    "national_id": "concat(repeat('*', greatest(length(v) - 4, 4)), right(v, 4))",
    "phone": "concat(repeat('*', greatest(length(v) - 4, 4)), right(v, 4))",
    "name": "concat(left(v, 1), '.')",
    "address": "sha2(v, 256)",
}


def masks_sql() -> str:
    pol = access.policy()["baseline"]
    clear_roles = [r for r, b in pol.items() if b.get("unmasked_pii")]
    lines = ["-- Column masks: personal data is shown in clear text only to roles with unmasked_pii: true",
             f"-- in access_policy.yaml ({', '.join(clear_roles)}), and only for their own domain.", ""]
    made = set()
    alters = []
    for c in contracts_mod.load_all():
        for p in c.properties:
            if not p.pii:
                continue
            groups = [grants.group_name(r, None if pol[r]["domains"] == "all" else c.domain) for r in clear_roles]
            check = " OR ".join(f"is_account_group_member('{g}')" for g in groups)
            dtype = TYPES.get(p.physical_type, "STRING")
            fn = f"{CATALOG}.{c.layer}.mask_{c.domain}_{p.pii}"
            if (fn, dtype) not in made:
                made.add((fn, dtype))
                masked = "CAST(NULL AS DOUBLE)" if dtype == "DOUBLE" else MASKS.get(p.pii, "sha2(v, 256)")
                lines.append(f"CREATE OR REPLACE FUNCTION {fn}(v {dtype}) RETURNS {dtype}\n"
                             f"  RETURN CASE WHEN {check} THEN v ELSE {masked} END;")
            alters.append(f"ALTER TABLE {_fq(c.name)} ALTER COLUMN {p.name} SET MASK {fn};")
    lv = access.levels()
    lines += ["", "-- Column-level classification: columns classified above their dataset return NULL to readers",
              "-- whose role baseline does not reach that level (Unity Catalog has no column GRANT).", ""]
    for c in contracts_mod.load_all():
        for p in c.properties:
            if not p.classification or lv[p.classification] <= lv[c.classification] or p.pii:
                continue
            groups = [grants.group_name(r, None if b["domains"] == "all" else c.domain) for r, b in pol.items()
                      if lv[b["up_to"]] >= lv[p.classification]]
            check = " OR ".join(f"is_account_group_member('{g}')" for g in groups)
            dtype = TYPES.get(p.physical_type, "STRING")
            fn = f"{CATALOG}.{c.layer}.mask_{c.domain}_{p.classification}_{dtype.lower()}"
            if (fn, dtype) not in made:
                made.add((fn, dtype))
                lines.append(f"CREATE OR REPLACE FUNCTION {fn}(v {dtype}) RETURNS {dtype}\n"
                             f"  RETURN CASE WHEN {check} THEN v ELSE CAST(NULL AS {dtype}) END;")
            alters.append(f"ALTER TABLE {_fq(c.name)} ALTER COLUMN {p.name} SET MASK {fn};")
    return BANNER + "\n".join(lines + [""] + alters) + "\n"


FILES = {
    "01_catalog_and_schemas.sql": catalog_sql,
    "02_tables_from_contracts.sql": tables_sql,
    "03_classification_tags.sql": tags_sql,
    "04_grants_from_policy.sql": grants_sql,
    "05_column_masks.sql": masks_sql,
}


def build(folder: Path | None = None) -> list[Path]:
    folder = folder or root() / "deploy" / "unity_catalog"
    folder.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, fn in FILES.items():
        path = folder / name
        path.write_text(fn(), encoding="utf-8")
        paths.append(path)
    return paths
