"""Generate human-readable documentation from the governance YAML and the run metadata.

Everything under ``docs/generated/`` is produced by ``govkit docs`` and must not be edited
by hand. CI regenerates it and fails if the committed copy is stale.
"""

from __future__ import annotations

import html
from pathlib import Path

from .paths import docs_dir, governance

HEADER = "<!-- Generated by `govkit docs`. Do not edit by hand. -->\n\n"


def out_dir() -> Path:
    path = docs_dir() / "generated"
    path.mkdir(parents=True, exist_ok=True)
    return path


def _write(name: str, text: str) -> Path:
    path = out_dir() / name
    path.write_text(HEADER + text.rstrip() + "\n", encoding="utf-8")
    return path


def operating_model() -> Path:
    roles = governance("roles")["roles"]
    acts = governance("raci")["activities"]
    lines = ["# Operating model: roles and RACI", "", "Source: `governance/roles.yaml`, `governance/raci.yaml`.", "",
             "## Roles", ""]
    for rid, r in roles.items():
        esc = roles[r["escalates_to"]]["name"] if r.get("escalates_to") else "—"
        lines += [f"### {r['name']} (`{rid}`)", "", r["purpose"], "", f"**Escalates to:** {esc}", "",
                  "**Responsibilities**", ""] + [f"- {x}" for x in r["responsibilities"]]
        lines += ["", "**Decisions**", ""] + [f"- {x}" for x in r["decisions"]] + [""]
    order = list(roles)
    lines += ["## RACI matrix", "", "R = Responsible · A = Accountable · C = Consulted · I = Informed", "",
              "| Activity | " + " | ".join(roles[r]["name"] for r in order) + " |",
              "|---|" + "|".join(":-:" for _ in order) + "|"]
    for a in acts:
        lines.append(f"| {a['name']} | " + " | ".join(a["raci"].get(r, "") for r in order) + " |")
    return _write("operating_model.md", "\n".join(lines))


def access_model() -> Path:
    from . import access, grants

    users = access.users()
    lv = access.levels()
    datasets = access.datasets()
    lines = ["# Access model", "",
             "Source: `governance/users.yaml`, `domains.yaml`, `classification.yaml`, `access_policy.yaml`.",
             "Default is **deny**; every cell below is derived from the policy.", "", "## Domains", "",
             "| Domain | Owner | Stewards |", "|---|---|---|"]
    for did, d in access.domains().items():
        lines.append(f"| {d['name']} (`{did}`) | {users[d['owner']]['name']} | "
                     + ", ".join(users[s]["name"] for s in d["stewards"]) + " |")
    lines += ["", "## Classification levels", "", "| Level | Rank | Handling |", "|---|:-:|---|"]
    for k, v in access.governance("classification")["levels"].items():
        lines.append(f"| {k} | {v['rank']} | {v['handling']} |")
    lines += ["", "## Role baseline (least privilege)", "", "| Role | Domains | Layers | Up to | Personal data |",
              "|---|---|---|---|---|"]
    for role, b in access.policy()["baseline"].items():
        lines.append(f"| {role} | {b['domains']} | {', '.join(b['layers'])} | {b['up_to']} | "
                     f"{'clear' if b.get('unmasked_pii') else 'masked'} |")
    lines += ["", "## Who can read what", "", "✔ = role baseline · ⏱ = time-bound approved request · blank = denied", "",
              "| Dataset | Class | " + " | ".join(u["name"] for u in users.values()) + " |",
              "|---|---|" + "|".join(":-:" for _ in users) + "|"]
    for ds in sorted(datasets, key=lambda d: (["bronze", "silver", "gold"].index(d["layer"]), d["name"])):
        cells = []
        for u in users.values():
            if access.role_allows(u, ds["domain"], ds["layer"], ds["classification"]):
                cells.append("✔")
            elif any(g["domain"] in ("*", ds["domain"]) and ds["layer"] in g["layers"]
                     and lv[ds["classification"]] <= lv[g["up_to"]]
                     for g in u.get("access", []) if g.get("basis") == "request"):
                cells.append("⏱")
            else:
                cells.append("")
        lines.append(f"| `{ds['name']}` | {ds['classification']} | " + " | ".join(cells) + " |")
    lines += ["", "## Compiled grants", "", "See [`access_grants.sql`](access_grants.sql)."]
    (out_dir() / "access_grants.sql").write_text(grants.render_postgres(), encoding="utf-8")
    return _write("access_model.md", "\n".join(lines))


def _anchor(term_id: str) -> str:
    return term_id.replace("_", "-")


def _card(t: dict, by_id: dict, users: dict) -> str:
    e = html.escape
    src = t.get("source") or {}
    search = " ".join([t["name"], t["definition"], *(t.get("synonyms") or [])]).lower()
    rows = []
    if t.get("formula"):
        rows.append(("Formula", f"<code>{e(t['formula'])}</code>"))
    if src:
        rows.append(("Source", f"<code>{e(src['table'])}.{e(src['column'])}</code>"))
    rows.append(("Domain", e(t["domain"])))
    rows.append(("Owner / Steward", f"{e(users.get(t['owner'], ''))} / {e(users.get(t['steward'], ''))}"))
    if t.get("synonyms"):
        rows.append(("Synonyms", e(", ".join(t["synonyms"]))))
    links = [f'<a href="#{_anchor(r)}">{e(by_id[r]["name"])}</a>' for r in t.get("related") or [] if r in by_id]
    if links:
        rows.append(("Related", " · ".join(links)))
    body = "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in rows)
    return (f'<article id="{_anchor(t["id"])}" data-text="{e(search)}"><h2>{e(t["name"])}'
            f'<span class="tag {t["type"]}">{t["type"]}</span><span class="tag {t["status"]}">{t["status"]}</span>'
            f"</h2><p>{e(t['definition'])}</p><dl>{body}</dl></article>")


def glossary() -> Path:

    terms = sorted(governance("glossary")["terms"], key=lambda t: t["name"].lower())
    users = {u["id"]: u["name"] for u in governance("users")["users"]}
    by_id = {t["id"]: t for t in terms}
    counts = {k: sum(1 for t in terms if t["type"] == k) for k in ("concept", "attribute", "metric")}
    lines = ["# Business glossary", "",
             f"{len(terms)} terms ({counts['concept']} concepts, {counts['attribute']} attributes, "
             f"{counts['metric']} metrics). Source: `governance/glossary.yaml`. "
             "Searchable version: [glossary.html](glossary.html).", "", "| Term | Domain | Type | Status |",
             "|---|---|---|---|"]
    lines += [f"| [{t['name']}](#{_anchor(t['id'])}) | {t['domain']} | {t['type']} | {t['status']} |" for t in terms]
    lines.append("")
    cards = []
    for t in terms:
        src = t.get("source") or {}
        rel = ", ".join(f"[{by_id[r]['name']}](#{_anchor(r)})" for r in t.get("related") or [] if r in by_id)
        dep = ", ".join(f"[{by_id[r]['name']}](#{_anchor(r)})" for r in t.get("depends_on") or [] if r in by_id)
        lines += [f'<a id="{_anchor(t["id"])}"></a>', f"## {t['name']}", "", t["definition"], "",
                  "| | |", "|---|---|",
                  f"| Type · status | {t['type']} · {t['status']} (next review {t['next_review']}) |",
                  f"| Domain | {t['domain']} |",
                  f"| Owner · Steward | {users.get(t['owner'], t['owner'])} · {users.get(t['steward'], t['steward'])} |"]
        if t.get("formula"):
            lines.append(f"| Formula | `{t['formula']}` |")
        if dep:
            lines.append(f"| Built from | {dep} |")
        if src:
            lines.append(f"| Source | `{src['table']}.{src['column']}` |")
        if t.get("quality_rules"):
            lines.append("| Quality rules | " + ", ".join(f"`{r}`" for r in t["quality_rules"]) + " |")
        if t.get("synonyms"):
            lines.append("| Synonyms | " + ", ".join(t["synonyms"]) + " |")
        if rel:
            lines.append(f"| Related | {rel} |")
        lines.append("")
        cards.append(_card(t, by_id, users))
    page = HTML_PAGE.replace("{{COUNT}}", str(len(terms))).replace("{{CARDS}}", "\n".join(cards))
    (out_dir() / "glossary.html").write_text(page, encoding="utf-8")
    return _write("glossary.md", "\n".join(lines))


